import { BlockTypes, ItemTypes } from "@minecraft/server";

export const DEFAULT_ITEM_ICON = "textures/ui/cancel";

export function cleanTexturePath(raw, fallback = DEFAULT_ITEM_ICON) {
    const s = String(raw ?? "").trim();
    if (!s) return fallback;
    return s.replace(/\.png$/i, "");
}

function safeIsValidItemId(id) {
    try {
        return !!ItemTypes.get(id);
    } catch {
        return false;
    }
}

function safeIsBlockId(id) {
    try {
        return !!BlockTypes.get(id);
    } catch {
        return false;
    }
}

export function normalizeLooseId(raw) {
    const s = String(raw ?? "")
        .trim()
        .toLowerCase();
    if (!s) return null;
    return s.includes(":") ? s : `minecraft:${s}`;
}

export function normalizeItemId(raw) {
    const id = normalizeLooseId(raw);
    return id && safeIsValidItemId(id) ? id : null;
}

export function shortItemName(id) {
    const s = String(id ?? "");
    if (s.startsWith("minecraft:")) return s.slice("minecraft:".length);
    const i = s.indexOf(":");
    return i !== -1 ? s.slice(i + 1) : s;
}

