function addCandidate(list, value) {
    if (value && !list.includes(value)) list.push(value);
}

function buildTextureCandidates(short) {
    const out = [];
    addCandidate(out, short);
    addCandidate(out, `${short}_carried`);

    for (const color of COLORS) {
        const prefix = `${color}_`;
        if (!short.startsWith(prefix)) continue;

        const rest = short.slice(prefix.length);
        const textureColor = color === "light_gray" ? "silver" : color;
        addCandidate(out, `${rest}_${color}`);
        addCandidate(out, `${rest}_${textureColor}`);
        addCandidate(out, `${rest}_${color}_carried`);
        addCandidate(out, `${rest}_${textureColor}_carried`);

        if (rest === "bundle") addCandidate(out, `bundle_${color}`);
        if (rest === "harness") addCandidate(out, `harness_${color}`);
        if (rest === "bed") addCandidate(out, `bed_${textureColor}`);
        if (rest === "dye") addCandidate(out, `dye_powder_${textureColor}`);
        if (rest === "carpet") addCandidate(out, `wool_colored_${textureColor}`);
        if (rest === "shulker_box") addCandidate(out, `shulker_top_${textureColor}`);
        if (rest === "glazed_terracotta") addCandidate(out, `glazed_terracotta_${textureColor}`);
        if (rest === "terracotta") addCandidate(out, `hardened_clay_stained_${textureColor}`);
        if (rest === "wool") addCandidate(out, `wool_colored_${textureColor}`);
        if (rest === "concrete") addCandidate(out, `concrete_${textureColor}`);
        if (rest === "concrete_powder") addCandidate(out, `concrete_powder_${textureColor}`);
        if (rest === "stained_glass") addCandidate(out, `glass_${textureColor}`);
        if (rest === "stained_glass_pane") addCandidate(out, `glass_pane_top_${textureColor}`);
    }

    for (const wood of Object.keys(PLANK_TEXTURE_CANDIDATES)) {
        const prefix = `${wood}_`;
        if (!short.startsWith(prefix)) continue;

        const rest = short.slice(prefix.length);
        if (["button", "pressure_plate", "fence", "fence_gate", "slab", "stairs"].includes(rest)) {
            for (const texture of PLANK_TEXTURE_CANDIDATES[wood]) addCandidate(out, texture);
        }

        if (rest === "door") {
            addCandidate(out, short);
            addCandidate(out, wood === "oak" ? "door_wood" : `door_${wood}`);
            if (wood === "dark_oak") addCandidate(out, "door_dark_oak");
        }

        if (rest === "trapdoor") addCandidate(out, wood === "oak" ? "trapdoor" : short);

        if (rest === "sign") {
            addCandidate(out, wood === "oak" ? "sign" : `sign_${wood}`);
            if (wood === "dark_oak") addCandidate(out, "sign_darkoak");
            for (const texture of PLANK_TEXTURE_CANDIDATES[wood]) addCandidate(out, texture);
        }

        if (rest === "hanging_sign") {
            addCandidate(out, `${wood}_hanging_sign`);
            addCandidate(out, `sign_${wood}_hanging`);
            if (wood === "dark_oak") addCandidate(out, "sign_darkoak_hanging");
        }

        if (rest === "boat") {
            addCandidate(out, `boat_${wood}`);
            addCandidate(out, `${wood}_boat`);
            if (wood === "dark_oak") addCandidate(out, "boat_darkoak");
        }

        if (rest === "chest_boat") addCandidate(out, `${wood}_chest_boat`);
        if (rest === "raft") addCandidate(out, `${wood}_raft`);
        if (rest === "chest_raft") addCandidate(out, `${wood}_chest_raft`);

        if (rest === "log" || rest === "wood") {
            if (wood === "oak") addCandidate(out, "log_oak");
            else if (wood === "dark_oak") addCandidate(out, "log_big_oak");
            else {
                addCandidate(out, `log_${wood}`);
                addCandidate(out, `${wood}_log_side`);
            }
        }

        if (rest === "planks") {
            for (const texture of PLANK_TEXTURE_CANDIDATES[wood]) addCandidate(out, texture);
        }

        if (rest === "leaves") {
            if (wood === "oak") {
                addCandidate(out, "leaves_oak_carried");
                addCandidate(out, "leaves_oak");
            } else if (wood === "dark_oak") {
                addCandidate(out, "leaves_big_oak_carried");
                addCandidate(out, "leaves_big_oak");
            } else {
                addCandidate(out, `leaves_${wood}_carried`);
                addCandidate(out, `leaves_${wood}`);
            }
        }
    }

    for (const suffix of ["_stairs", "_slab", "_wall", "_button", "_pressure_plate", "_fence_gate", "_fence"]) {
        if (!short.endsWith(suffix)) continue;
        const base = short.slice(0, -suffix.length);
        addCandidate(out, base);
        for (const texture of BASE_MATERIAL_TEXTURE_CANDIDATES[base] ?? []) addCandidate(out, texture);
    }

    if (short.startsWith("cooked_")) {
        addCandidate(out, `${short.slice("cooked_".length)}_cooked`);
    } else {
        const rawFood = {
            beef: "beef_raw",
            porkchop: "porkchop_raw",
            chicken: "chicken_raw",
            mutton: "mutton_raw",
            rabbit: "rabbit_raw",
            cod: "fish_raw",
            salmon: "fish_salmon_raw",
            tropical_fish: "fish_clownfish_raw",
            pufferfish: "fish_pufferfish_raw",
        }[short];
        addCandidate(out, rawFood);
    }

    if (short === "cooked_cod") addCandidate(out, "fish_cooked");
    if (short === "cooked_salmon") addCandidate(out, "fish_salmon_cooked");

    if (short.endsWith("_bucket")) {
        const thing = short.slice(0, -"_bucket".length);
        const bucketName =
            {
                water: "water",
                lava: "lava",
                milk: "milk",
                powder_snow: "powder_snow",
                cod: "cod",
                salmon: "salmon",
                tropical_fish: "tropical",
                pufferfish: "pufferfish",
                axolotl: "axolotl",
                tadpole: "tadpole",
            }[thing] ?? thing;
        addCandidate(out, `bucket_${bucketName}`);
    }
    if (short === "bucket") addCandidate(out, "bucket_empty");

    if (short.startsWith("music_disc_")) {
        addCandidate(out, `record_${short.slice("music_disc_".length)}`);
    }

    if (short.endsWith("_spawn_egg")) {
        const mob = short.slice(0, -"_spawn_egg".length);
        addCandidate(out, `spawn_egg_${mob}`);
        addCandidate(out, `egg_${mob.replace(/_/g, "")}`);
    }

    if (short.startsWith("golden_")) {
        const rest = short.slice("golden_".length);
        addCandidate(out, `gold_${rest}`);
        addCandidate(out, `${rest}_golden`);
    }

    if (short.endsWith("_horse_armor")) {
        const material = short.slice(0, -"_horse_armor".length);
        addCandidate(out, `${material === "golden" ? "gold" : material}_horse_armor`);
    }

    addCandidate(out, DIRECT_NAME_RENAMES[short]);
    addCandidate(out, FLOWER_TEXTURE_CANDIDATES[short]);
    return out;
}

function firstMappedPath(mapping, names) {
    for (const name of names) {
        const path = mapping[name];
        if (path) return path;
    }
    return null;
}

function findItemTexture(short, candidates) {
    return (
        VANILLA_ITEM_ALIAS_PATHS[short] ??
        firstMappedPath(VANILLA_ITEM_ALIAS_PATHS, candidates) ??
        firstMappedPath(VANILLA_ITEM_BASENAME_PATHS, candidates)
    );
}

function findTerrainTexture(short, candidates) {
    const carried = [`${short}_carried`, ...candidates.filter((name) => name.endsWith("_carried"))];
    return (
        firstMappedPath(VANILLA_TERRAIN_ALIAS_PATHS, carried) ??
        VANILLA_TERRAIN_ALIAS_PATHS[short] ??
        firstMappedPath(VANILLA_TERRAIN_ALIAS_PATHS, candidates) ??
        firstMappedPath(VANILLA_TERRAIN_BASENAME_PATHS, candidates)
    );
}

function resolveVanillaTexturePath(itemId) {
    const short = shortItemName(itemId);
    const candidates = buildTextureCandidates(short);
    const isBlock = safeIsBlockId(itemId);

    if (isBlock) {
        return findTerrainTexture(short, candidates) ?? findItemTexture(short, candidates) ?? DEFAULT_ITEM_ICON;
    }

    return findItemTexture(short, candidates) ?? findTerrainTexture(short, candidates) ?? DEFAULT_ITEM_ICON;
}

function populateRegisteredVanillaOverrides() {
    let registered = [];
    try {
        registered = ItemTypes.getAll();
    } catch {
        return;
    }

    for (const type of registered) {
        const id = normalizeLooseId(type?.id);
        if (!id?.startsWith("minecraft:") || ITEM_TEXTURE_OVERRIDES[id]) continue;
        ITEM_TEXTURE_OVERRIDES[id] = cleanTexturePath(resolveVanillaTexturePath(id), DEFAULT_ITEM_ICON);
    }
}

populateRegisteredVanillaOverrides();
Object.freeze(ITEM_TEXTURE_OVERRIDES);

export function guessTexturePathFromItemId(itemId) {
    const id = normalizeItemId(itemId);
    if (!id) return DEFAULT_ITEM_ICON;
    return ITEM_TEXTURE_OVERRIDES[id] ?? resolveVanillaTexturePath(id) ?? DEFAULT_ITEM_ICON;
}

export function getItemIconFromId(itemId) {
    return cleanTexturePath(guessTexturePathFromItemId(itemId), DEFAULT_ITEM_ICON);
}

export function getItemIconFromShopItem(it) {
    const id = normalizeItemId(it?.template?.typeId ?? it?.id);
    if (!id) return DEFAULT_ITEM_ICON;
    return getItemIconFromId(id);
}

export function getItemIconFromAuction(auctionOrTemplate) {
    const t = auctionOrTemplate?.template ?? auctionOrTemplate;
    const id = normalizeItemId(t?.typeId ?? t?.id);
    if (!id) return DEFAULT_ITEM_ICON;
    return getItemIconFromId(id);
}

export function getStackIcon(stack) {
    if (!stack) return "textures/ui/cancel";
    return getItemIconFromId(stack.typeId);
}
